# .upper() - ს გადაჰყავს lowercase ასოები uppercase - ში. მაგალითად:
print("football".upper())
print("basketball".upper())
print("volleyball".upper())
# .lower() - ს გადაჰყავს uppercase ასოები lowercase - ში. მაგალითად:
print("FOOTBALL".lower())
print("BASKETBALL".lower())
print("VOLLEYBALL".lower())
# .capitalize() გადაიყვანს მთლიანი string - ის პირველ ასოს uppercase - ში და დანარჩენს lowercase - ში. მაგალითად:
print("football".capitalize())
print("basketball".capitalize())
print("volleyball".capitalize())
# .title() გადაიყვანს string - ის თითოეული სიტყვის პირველ ასოს uppercase - ში. მაგალითად:
print("football is fun".title())
print("basketball is fun".title())
print("volleyball is fun".title())
# .find() ეძებს მითითებული სიმბოლოს ინდექსის პოზიციას მოცემულ string - ში. მაგალითად:
print("football".find("o"))
print("basketball".find("t"))
print("volleyball".find("b"))

